/**
 * `npm run evaluate` — writes evaluation/results/latest.json and
 * evaluation/RESULTS.md from a real run of the rule engine. Numbers in the
 * report are computed here, never typed by hand.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { evaluate, RULE_IDS, type Metrics } from "./evaluate";

const RULE_NAMES: Record<string, string> = {
  "overdue-follow-up": "R1 Overdue follow-up",
  "lab-result-missing": "R2 Lab result missing",
  "referral-outcome-missing": "R3 Referral outcome missing",
  "persistent-symptom-unresolved": "R4 Persistent symptom without plan",
};

const pct = (value: number | null) => (value === null ? "n/a" : `${(value * 100).toFixed(1)}%`);
const row = (name: string, m: Metrics) =>
  `| ${name} | ${m.units} | ${m.tp} | ${m.fp} | ${m.fn} | ${m.tn} | ${pct(m.precision)} | ${pct(m.recall)} | ${pct(m.f1)} | ${pct(m.falsePositiveRate)} |`;

const result = evaluate();
mkdirSync("evaluation/results", { recursive: true });
writeFileSync("evaluation/results/latest.json", `${JSON.stringify(result, null, 2)}\n`);

const errors = result.units.filter((unit) => unit.outcome === "FP" || unit.outcome === "FN");
const header = "| Scope | Units | TP | FP | FN | TN | Precision | Recall | F1 | FPR |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|";
const report = `# Detection evaluation results

> Generated by \`npm run evaluate\` on ${result.generatedAt.slice(0, 10)}. Do not edit numbers by hand — rerun the script.
> Independent check: \`python3 research/verify_metrics.py\` recomputes every metric from \`evaluation/results/latest.json\`.

**Synthetic data only.** These figures describe agreement between rule engine v${result.rulesVersion} and reference labels
(${result.labelSetVersion}) on a small, purpose-built fictional dataset. They say nothing about real-world clinical performance.

## Setup

- Dataset: ${result.dataset.patients} fictional patients in ${result.dataset.clinics} clinics (\`src/data/synthetic\`).
- Evaluation date (as-of): \`${result.asOf}\`; all record dates are offsets from it.
- Reference units: ${result.dataset.units} pre-declared units, ${result.dataset.positiveUnits} labeled as real gaps (\`evaluation/reference-labels.ts\`).
- Rule configuration: R1 grace ${result.config.overdueFollowUp.graceDays} d · R2 grace ${result.config.labResultMissing.graceDays} d · R3 grace ${result.config.referralOutcomeMissing.sentGraceDays} d / post-visit ${result.config.referralOutcomeMissing.postVisitRecordsDays} d · R4 ≥${result.config.persistentSymptom.minEncounters} visits over ≥${result.config.persistentSymptom.minSpanDays} d.
- Unlisted predictions (findings matching no declared unit, counted as FP): ${result.unlistedPredictions.length ? result.unlistedPredictions.map((item) => `\`${item}\``).join(", ") : "none"}.

## Unit-level results

${header}
${RULE_IDS.map((ruleId) => row(RULE_NAMES[ruleId], result.perRule[ruleId])).join("\n")}
${row("**All rules**", result.overall)}

FPR = FP / (FP + TN) over the declared candidate units. "n/a" means the denominator is zero.

## Patient-level results

A patient is positive if any of their units is labeled a real gap; predicted positive if the engine emits any finding for them.

${header}
${row("Patients", result.patientLevel)}

## Disagreements

| Outcome | Rule | Subject | Reference rationale |
|---|---|---|---|
${errors.map((unit) => `| ${unit.outcome} | ${RULE_NAMES[unit.ruleId]} | \`${unit.subjectId}\` | ${unit.rationale} |`).join("\n")}

## How to read this — limitations

1. **Tiny, synthetic, and self-authored.** ${result.dataset.patients} patients and ${result.dataset.units} units are far too few for stable estimates; one changed label moves precision or recall by several points. No confidence intervals are reported because they would be uninformatively wide.
2. **Not independent.** The rules (PRODUCT_SPEC §6) and the reference labels were written by the same team (Claude), and — because the Codex implementer ran out of quota — the engine was also implemented by Claude, who had seen the labels. Mitigations: the rule specification and the labels were committed *before* any engine code (git history), the engine implements the written spec without dataset-specific tuning, and labels encode clinical judgment rather than the rules (so several intentional disagreements exist). Results are still likely optimistic.
3. **The errors are the planted ones.** Every disagreement below is a challenge case the dataset author deliberately designed to defeat v1 rules, and the totals match the author's expectations before the engine existed. That confirms the engine implements its specification — it does not show how the rules would perform on unanticipated real-world documentation.
4. **Scenario coverage, not prevalence.** The dataset over-represents edge cases (boundary windows, synonyms, free-text plans, reconciled outside results) to stress the rules. Metrics here do not estimate how often gaps occur or are caught in a real clinic.
5. **Known v1 blind spots, visible in the false negatives:** structured-field dependence (free-text follow-up plans are invisible), exact symptom-code matching (synonyms are not merged), and trusting "resulted" lab status even when the result note asks for a redraw.
6. **Known false-positive sources:** results filed under a duplicate order, and outcomes documented only in a later visit note while the referral status was never updated. These are real documentation-hygiene issues, but clinicians would not consider them open care gaps.
7. **Required before any real use:** retrospective validation on de-identified real records with independent, blinded clinician labelers (≥2 with adjudication), inter-rater agreement, subgroup analysis, and a prospective silent-mode pilot. See \`docs/CLINICAL_DEPLOYMENT_CHECKLIST.md\` §5.
`;
writeFileSync("evaluation/RESULTS.md", report);

const o = result.overall;
console.log(`Evaluation (${result.dataset.units} units, as of ${result.asOf.slice(0, 10)}): precision ${pct(o.precision)}, recall ${pct(o.recall)}, F1 ${pct(o.f1)}, FPR ${pct(o.falsePositiveRate)}`);
console.log(`TP ${o.tp} · FP ${o.fp} · FN ${o.fn} · TN ${o.tn} · unlisted predictions ${result.unlistedPredictions.length}`);
console.log("Wrote evaluation/results/latest.json and evaluation/RESULTS.md");
