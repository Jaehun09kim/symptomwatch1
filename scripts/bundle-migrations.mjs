// Embeds db/migrations/*.sql into a TypeScript module so the server never
// reads the filesystem for migrations (keeps serverless bundles small).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = "db/migrations";
const files = readdirSync(dir).filter((name) => /^\d+_[\w-]+\.sql$/.test(name)).sort();
const entries = files.map((name) => `  { name: ${JSON.stringify(name)}, contents: ${JSON.stringify(readFileSync(`${dir}/${name}`, "utf8"))} },`);
const output = `// GENERATED by scripts/bundle-migrations.mjs from db/migrations — do not edit.\nexport const bundledMigrations: ReadonlyArray<{ name: string; contents: string }> = [\n${entries.join("\n")}\n];\n`;
writeFileSync("src/lib/db/migrations.generated.ts", output);
console.log(`Bundled ${files.length} migrations.`);
